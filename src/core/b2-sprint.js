function asDateKey(value) {
  if (typeof value === 'string') return value;
  const y = value.getFullYear();
  const m = String(value.getMonth() + 1).padStart(2, '0');
  const d = String(value.getDate()).padStart(2, '0');
  return `${y}-${m}-${d}`;
}

function daysBetween(from, to) {
  return Math.round((Date.parse(`${to}T00:00:00Z`) - Date.parse(`${from}T00:00:00Z`)) / 86400000);
}

export function b2Sprint(date = new Date()) {
  const current = asDateKey(date);
  const todayTask = PLAN.find((item) => item.date === current)
    || PLAN.find((item) => item.date > current)
    || null;
  return {
    task: todayTask,
    daysLeft: Math.max(0, daysBetween(current, B2_EXAM_DATE)),
    examPassed: current >= B2_EXAM_DATE,
  };
}
